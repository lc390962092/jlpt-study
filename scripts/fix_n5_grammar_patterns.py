def main():
    with open(PATH, 'r', encoding='utf-8') as f:
        data = json.load(f)

    # Backup
    with open(BACKUP, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    fixed_pat = 0
    fixed_usage = 0
    for g in data:
        grammar = g.get('grammar', '').strip()

        if grammar in PATTERNS and g.get('pattern') != PATTERNS[grammar]:
            g['pattern'] = PATTERNS[grammar]
            fixed_pat += 1

        if grammar in PATTERNS:
            desc = g.get('description', '')
            new_pat = PATTERNS[grammar]
            if '【接续】' in desc:
                new_desc = re.sub(r'【接续】[^\n]+', f'【接续】{new_pat}', desc)
                if new_desc != desc:
                    g['description'] = new_desc
            else:
                g['description'] = f'【接续】{new_pat}\n\n' + desc

        if grammar in USAGES:
            desc = g.get('description', '')
            new_usage = USAGES[grammar]
            if '【用法】' in desc:
                new_desc = re.sub(r'【用法】[^\n]+', f'【用法】{new_usage}', desc)
                if new_desc != desc:
                    g['description'] = new_desc
                    fixed_usage += 1
            else:
                # Add usage line if missing
                g['description'] = desc + f'\n\n【用法】{new_usage}'
                fixed_usage += 1

    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f'Fixed {fixed_pat} pattern entries, {fixed_usage} usage entries.')
    print(f'Backup saved to {BACKUP}')


if __name__ == '__main__':
    main()
