def lookup_pattern(grammar: str) -> str:
    # 精确匹配优先
    if grammar in PATTERN_MAP:
        return PATTERN_MAP[grammar]
    # 按 key 长度降序，找最长包含匹配，避免短 key 覆盖长 key
    for key in sorted(PATTERN_MAP.keys(), key=len, reverse=True):
        if key == grammar:
            return PATTERN_MAP[key]
        # 只有当 grammar 是 key 的真子串，或 key 是 grammar 的真子串时匹配
        if grammar in key or key in grammar:
            return PATTERN_MAP[key]
    return ""


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    total = 0
    filled = 0
    missing = []

    for g in data:
        total += 1
        gp = g.get("grammar", "")
        pattern = lookup_pattern(gp)
        if pattern:
            g["pattern"] = pattern
            filled += 1
        else:
            missing.append(gp)

    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Total: {total}, filled pattern: {filled}, missing: {len(missing)}")
    if missing:
        print("Missing items:")
        for m in missing:
            print(f"  - {m}")


if __name__ == "__main__":
    main()
