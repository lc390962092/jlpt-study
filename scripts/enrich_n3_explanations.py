def fallback_explanation(answer, question):
    return "「{}」是本题的正确语法形式。请结合题干「{}」的语境，判断该形式在句中的语法功能。".format(answer, question)


def enrich_explanations():
    data = json.loads(EXAM_PATH.read_text(encoding="utf-8"))
    changed = 0
    missing = []

    for sec in data.get("sections", []):
        for q in sec.get("questions", []):
            options = q.get("options", [])
            answer_idx = q.get("answer", 0)
            if answer_idx is None or answer_idx >= len(options):
                continue
            answer = options[answer_idx]
            exp = TEMPLATES.get(answer)
            if exp:
                q["explanation"] = exp
                changed += 1
            else:
                q["explanation"] = fallback_explanation(answer, q.get("question", ""))
                missing.append(answer)

    OUT_PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print("Updated {} explanations, {} fallback".format(changed, len(missing)))
    if missing:
        for ans in sorted(set(missing)):
            print("  - {}".format(ans))


if __name__ == "__main__":
    enrich_explanations()
