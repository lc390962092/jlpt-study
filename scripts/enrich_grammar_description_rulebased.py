def build_mistakes(category: str, compare: str) -> str:
    lines = ["• " + m for m in MISTAKE_TEMPLATES.get(category, MISTAKE_TEMPLATES['general'])]
    if compare and compare.strip() and '注意' not in compare:
        lines.append("• 忽视与近义表达的区分：" + compare.strip())
    return '\n'.join(lines)


