def classify_grammar(grammar: str, pattern: str, meaning: str) -> str:
    g = grammar.strip().replace('〜', '').replace('~', '').replace('…', '')
    p = pattern.lower()
    m = meaning.lower()
    text = (g + ' ' + p + ' ' + m)

    # Copula first (polite/plain judgement)
    if any(k in text for k in ['です', 'ます', 'だ']):
        return 'copula'

    if any(k in text for k in ['たい', 'たがる', 'てほしい', 'てもらう', 'てくれる', 'てあげる', 'られる', 'れる', 'せる', 'させる']):
        return 'auxiliary_verb'
    if any(k in text for k in ['ていく', 'てくる', 'ておく', 'てしまう', 'てみる', 'てある']):
        return 'te_auxiliary'
    if 'ない' in text and any(k in text for k in ['ないで', 'なければ', 'なくて', 'なくちゃ', 'なくては']):
        return 'negative'
    if 'ば' in text or 'たら' in text or 'なら' in text or 'と（' in text:
        return 'conditional'
    if 'のに' in text or 'のを' in text or 'のが' in text or 'こと' in text or 'もの' in text:
        return 'nominalisation'
    if 'と' in text and any(k in text for k in ['ついで', 'たび', '度', 'たら', 'ともに', 'にともなって', 'について']):
        return 'particle_phrase'
    if 'から' in text or 'ので' in text or 'ため' in text or 'おかげ' in text or 'せい' in text:
        return 'causative_reason'
    if 'まで' in text or 'までに' in text or '前に' in text or '後で' in text or '間' in text or 'うちに' in text:
        return 'time'
    if 'ように' in text or 'ような' in text or 'よう' in text or 'そうだ' in text or 'らしい' in text or 'みたい' in text:
        return 'conjecture'
    if '方' in text or 'ほうが' in text or 'より' in text or 'ほど' in text or 'くらい' in text:
        return 'comparison'
    if 'は' in text and 'が' in text:
        return 'particle'
    if 'に' in text or 'で' in text or 'を' in text or 'へ' in text or 'から' in text or 'まで' in text:
        return 'particle'
    if 'にわたって' in text or 'を通じて' in text or 'にとって' in text or 'について' in text or 'に対して' in text:
        return 'particle_phrase'
    if 'です' in text or 'ます' in text or 'だ' in text:
        return 'copula'
    if 'い形容詞' in pattern or 'な形容詞' in pattern:
        return 'adjective'
    return 'general'


