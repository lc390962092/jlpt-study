def clean_grammar_key(g: str) -> str:
    return g.strip().replace('〜', '').replace('~', '').replace('…', '').replace(' ', '')


def get_extra_examples(grammar: str) -> list:
    key = clean_grammar_key(grammar)
    return EXTRA_EXAMPLES.get(key, [])


def build_examples(entry: dict) -> str:
    lines = []
    lines.append(entry['example'])
    if entry.get('example_reading'):
        lines.append(f"読み：{entry['example_reading']}")
    if entry.get('example_meaning'):
        lines.append(f"訳：{entry['example_meaning']}")

    extras = get_extra_examples(entry['grammar'])
    for ex, read, trans in extras[:2]:
        lines.append('')
        lines.append(ex)
        lines.append(f"読み：{read}")
        lines.append(f"訳：{trans}")

    return '\n'.join(lines)


def build_compare(compare: str, grammar: str, meaning: str) -> str:
    if compare and compare.strip():
        c = compare.strip()
        c = re.sub(r'注意与近义表达在接续、语气及使用场景上的差异[。]?', '', c)
        c = c.strip()
        if c:
            return c
    return f"注意与近义表达在接续和语气上的差异。"


def enrich_entry(entry: dict) -> dict:
    category = classify_grammar(entry['grammar'], entry.get('pattern', ''), entry.get('meaning', ''))
    usage = build_usage(category, entry.get('meaning', ''), entry.get('pattern', ''))
    mistakes = build_mistakes(category, entry.get('compare', ''))
    examples = build_examples(entry)
    compare = build_compare(entry.get('compare', ''), entry['grammar'], entry.get('meaning', ''))

    desc = (
        f"【接续】{entry.get('pattern', '')}\n\n"
        f"【含义】{entry.get('meaning', '')}\n\n"
        f"【用法】{usage}\n\n"
        f"【例句】\n{examples}\n\n"
        f"【常见错误】\n{mistakes}\n\n"
        f"【注意／对比】{compare}"
    )
    entry['description'] = desc
    return entry


def enrich_file(level: str, dry_run: bool = False):
    path = CONTENT_DIR / f"{level}_grammar.json"
    backup = CONTENT_DIR / f"{level}_grammar.json.bak.rulebased"
    if not path.exists():
        print(f"File not found: {path}")
        return

    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    with open(backup, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    enriched = [enrich_entry(e) for e in data]

    if not dry_run:
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(enriched, f, ensure_ascii=False, indent=2)
        print(f"Wrote {len(enriched)} entries to {path}")
    else:
        print(f"Dry run: would write {len(enriched)} entries to {path}")


def preview(level: str, n: int = 3):
    path = CONTENT_DIR / f"{level}_grammar.json"
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    for e in data[:n]:
        print(f"\n=== {e['id']} {e['grammar']} ===")
        print(e['description'][:1200])


