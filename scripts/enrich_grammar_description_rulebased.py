def build_usage(category: str, meaning: str, pattern: str) -> str:
    base = USAGE_TEMPLATES.get(category, USAGE_TEMPLATES['general'])
    if meaning and '（' in meaning:
        core = meaning.split('（')[0].strip('。')
    else:
        core = meaning.strip('。')
    return f"{base}本条目核心含义为「{core}」。"


